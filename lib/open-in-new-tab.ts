/**
 * Открывает путь/URL в новой вкладке — для ссылок на юридические документы
 * (оферта, политика конфиденциальности и т.п.), которые не должны прерывать
 * текущий флоу (регистрацию, заполнение формы). Тот же приём, что уже
 * использовался для внешних ссылок на партнёров в site-footer.tsx.
 */
export function openInNewTab(path: string): void {
  window.open(path, '_blank', 'noopener,noreferrer');
}
